import astropy.units as u
import numpy as np

# ── Input parameters ────────────────────────────────────────────────────────
M_star  = 1.0 * u.M_sun
alpha   = 1e-3           # Shakura-Sunyaev dimensionless viscosity
h       = 0.05           # H/R aspect ratio (isothermal, at r = 20 au)
M_p_ref = 1.0 * u.M_jup  # reference planet mass for gap-depth evaluation

# ── Mass ratio ───────────────────────────────────────────────────────────────
q = (M_p_ref / M_star).decompose().value   # q = 9.546e-4 for 1 MJup / 1 Msun

# ── Kanagawa K parameter ─────────────────────────────────────────────────────
# K = q² h⁻⁵ α⁻¹   [Kanagawa+2016, eq.4; Kanagawa+2017, eq.7]
K = q**2 / (h**5 * alpha)

# ── Gap depth (Kanagawa 2016 eq.4) ───────────────────────────────────────────
Sigma_ratio = 1.0 / (1.0 + 0.04 * K)   # Σ_gap / Σ_0

# ── Thermal gap-opening mass: R_Hill = H ─────────────────────────────────────
# R_H = a (q/3)^{1/3} = h a  ⟹  q_th = 3 h³
M_gap_thermal = (3 * M_star * h**3).to(u.M_jup)

# ── Kanagawa viscous gap-opening mass: K = 25 ────────────────────────────────
# Σ_gap/Σ_0 = 0.5 when K_open = 25  ⟹  q_visc = sqrt(25 h⁵ α)
K_open    = 25.0
M_gap_visc = (np.sqrt(K_open * h**5 * alpha) * M_star).to(u.M_jup)

